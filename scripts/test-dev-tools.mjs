import assert from 'node:assert/strict';
import { EmbeddedAuthority } from '../src/core/embedded-session.js';
import { TEST_FIELD_SESSION_CONFIG } from '../src/core/session-config.js';
import { reactorQuote } from '../src/core/research.js';
const a = new EmbeddedAuthority(TEST_FIELD_SESSION_CONFIG);
a.join({ clientId: 'dev', payload: { label: 'dev' } });
const player = a.state.players[0];
const cmd = (payload) => ({ clientId: 'dev', playerId: player.id, sequence: 1, payload });
const set = (payload) => a.setDevTools(cmd(payload), player);
a.setDevTools(cmd({ option: 'infiniteMoney', enabled: true }), { id: 'guest' });
assert.equal(a.state.dev, undefined);
set({ option: 'infiniteMoney', enabled: true });
const wallet = a.state.economyByPlayer[player.id]; wallet.credits = 0;
const area = a.map.defenseAreas[0];
a.placeTower(cmd({ definitionId: 'frame', x: area.shape.x, y: area.shape.y }), player);
assert.equal(a.state.towers.length, 1); assert.equal(wallet.credits, 0);
const station = a.normalizeTower({ id: 'research', ownerId: player.id, definitionId: 'arsenal', areaId: area.id, x: area.shape.x + 40, y: area.shape.y });
a.state.towers.push(station);
a.purchaseResearch(cmd({ towerId: station.id, researchId: 1, expectedCost: 10000 }), player);
assert.ok(a.state.research.unlocked.includes(1)); assert.equal(wallet.credits, 0);
station.definitionId = 'reactor';
a.purchaseReactor(cmd({ towerId: station.id, categoryId: 'damage', expectedRank: 0, expectedCost: reactorQuote(a.state, 'damage').cost }), player);
assert.equal(a.state.research.reactor.damage, 1); assert.equal(wallet.credits, 0);
set({ option: 'infiniteMoney', enabled: false });
a.placeTower(cmd({ definitionId: 'frame', x: area.shape.x - 40, y: area.shape.y }), player);
assert.equal(a.state.towers.length, 2);
set({ option: 'infiniteHealth', enabled: true });
const lives = a.state.base.lives; a.recordBreaches(lives + 100);
assert.equal(a.state.base.lives, lives);
set({ option: 'infiniteHealth', enabled: false }); a.recordBreaches(lives);
assert.equal(a.state.phase, 'defeated');
set({ action: 'healBase' }); assert.equal(a.state.phase, 'running');
set({ option: 'paused', enabled: true }); const tick = a.state.runTick; a.tick();
assert.equal(a.state.runTick, tick);
set({ option: 'paused', enabled: false });
set({ option: 'stopSpawns', enabled: true });
for (let i = 0; i < 120; i++) a.tick();
assert.equal(a.swarm.count, 0);
a.swarm.spawnOne({ x: 0, y: -500, spreadX: 0, spreadY: 0 }, 1);
set({ action: 'clearEnemies' }); assert.equal(a.swarm.count, 0);
const restored = new EmbeddedAuthority(TEST_FIELD_SESSION_CONFIG);
restored.applyCorrectionSnapshot(a.correctionSnapshot());
assert.deepEqual(restored.state.dev, a.state.dev);
console.log('dev tools: host gate, free purchases, health, revive, pause, spawns, clear and correction passed');
